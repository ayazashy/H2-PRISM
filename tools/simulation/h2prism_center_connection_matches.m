function connected = h2prism_center_connection_matches(peers, expectedSID, resolveSID, endpoints, expectedEndpoints)
% Require one exact Simscape peer and independently matching line endpoints.
connected = isstruct(peers) && isscalar(peers) && isfield(peers,'Block') && ...
    ((isstring(peers.Block) && isscalar(peers.Block) && ~ismissing(peers.Block)) || ...
     (ischar(peers.Block) && isrow(peers.Block))) && ~isempty(char(peers.Block)) && ...
    isequal(endpoints,expectedEndpoints) && strcmp(resolveSID(peers.Block),expectedSID);
end
