#!/usr/bin/env python3
"""
Writes the CANDIDATE protocol 2.0 config (06_audit_preparation/protocol2/CANDIDATE_PROTOCOL_2_0.yaml) as an explicit,
reviewable diff of the pinned protocol 1.1 config. Status CANDIDATE_PROTOCOL_2_0_NOT_APPROVED: the runner's preflight
refuses it in every mode (config_status check) until owners approve it, a new status is set and the project lead
authorizes a run. Nothing here is tuned on R2 or any held-out result.

Usage: python tools/dataset/build_candidate_protocol_2_0.py   (after tools/dataset/build_candidate_manifest_v03.py)
"""

from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
BASE = REPO / "06_audit_preparation" / "FINAL_EXPERIMENT_CONFIG.yaml"
OUT = REPO / "06_audit_preparation" / "protocol2"
COMMON_CHANNELS = ["PS1", "PS2", "PS3", "PS4", "PS5", "PS6", "PS7", "PS8", "PS9", "PS10", "MFS1", "MFS2", "MFS3"]
STATUS = "CANDIDATE_PROTOCOL_2_0_NOT_APPROVED"


def _sha(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def build() -> dict:
    base = yaml.safe_load(BASE.read_text(encoding="utf-8"))
    c = copy.deepcopy(base)
    man, folds = OUT / "CANDIDATE_MANIFEST_V03.csv", OUT / "CANDIDATE_OUTER_FOLDS_V03.csv"
    changes = {
        "status": STATUS,
        "version": "candidate-protocol-2.0",
        "derived_from": {"file": BASE.relative_to(REPO).as_posix(), "sha256": _sha(BASE)},
        "dataset.manifest": {"file": man.relative_to(REPO).as_posix(), "sha256": _sha(man)},
        "dataset.topology_column": "topology_source_model",                                  # P2-A (needs R-18 option B)
        "splits.outer": {"file": folds.relative_to(REPO).as_posix(), "sha256": _sha(folds), "design": "leave_one_topology_out"},
        "splits.inner": {"scheme": "LOTO_within_train", "note": "derived by the runner; pinned record generated at activation"},
        "features.channels": COMMON_CHANNELS,                                                 # P2-B
        "distinguishability.support_unit": "independence_group",                              # P2-C
        "distinguishability.weighting": "inverse_distance",                                   # FA-09: finer D resolution
        "policy_primary.evidence_conflict": "ambiguity_pair",                                 # P2-D
        "combined_scores.on_undefined": "not_estimable",                                      # P2-F
        "thresholds.target_rule": {"rule": "h2prism.protocol2.development_target", "margin": 0.05, "min_target": 0.3,
                                   "grid": [0.9, 0.8, 0.7, 0.6, 0.5, 0.4, 0.3],
                                   "note": "operating targets fixed from DEVELOPMENT attainability before any outer evaluation (P2-E)"},
    }
    for k, v in changes.items():
        if "." in k:
            a, b = k.split(".", 1)
            c.setdefault(a, {})[b] = v
        else:
            c[k] = v
    c["registered_targets_protocol_1_1"] = {"primary": base["thresholds"]["target_coverage_primary"],
                                           "secondary": base["thresholds"].get("target_coverage_secondary"),
                                           "note": "historical registered targets of protocol 1.1; RQ1 was NOT_ESTIMABLE at all of them"}
    OUT.mkdir(parents=True, exist_ok=True)
    p = OUT / "CANDIDATE_PROTOCOL_2_0.yaml"
    header = ("# CANDIDATE protocol 2.0 - NOT APPROVED, NOT EXECUTABLE (preflight refuses status " + STATUS + ").\n"
              "# Generated by tools/dataset/build_candidate_protocol_2_0.py from the pinned protocol 1.1 config.\n"
              "# Every change is listed in CANDIDATE_PROTOCOL_2_0_DIFF.json with its forensic justification.\n")
    p.write_text(header + yaml.safe_dump(c, sort_keys=False), encoding="utf-8")
    diff = {"status": STATUS, "base_config_sha256": _sha(BASE), "candidate_sha256": _sha(p),
            "changes": {k: v for k, v in changes.items()},
            "justification": {"dataset.topology_column": "FA-01", "features.channels": "FA-02", "distinguishability.support_unit": "FA-03",
                              "distinguishability.weighting": "FA-09", "policy_primary.evidence_conflict": "FA-05",
                              "combined_scores.on_undefined": "FA-08", "thresholds.target_rule": "FA-07"}}
    (OUT / "CANDIDATE_PROTOCOL_2_0_DIFF.json").write_text(json.dumps(diff, indent=2, default=str) + "\n", encoding="utf-8")
    return diff


if __name__ == "__main__":
    d = build()
    print(json.dumps({"status": d["status"], "n_changes": len(d["changes"]), "candidate_sha256": d["candidate_sha256"][:12]}, indent=2))
