export function initIconSprite() {
  if (typeof document === 'undefined' || document.getElementById('ico-sprite')) return;
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.id = 'ico-sprite';
  svg.setAttribute('style', 'position:absolute;width:0;height:0;overflow:hidden');
  svg.setAttribute('aria-hidden', 'true');
  svg.innerHTML = Object.entries(SYMBOLS)
    .map(
      ([id, body]) =>
        `<symbol id="i-${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`
    )
    .join('');
  document.body.prepend(svg);
}

export function ico(name, extraClass = '') {
  const id = SYMBOLS[name] ? name : 'circle';
  return `<svg class="ico ${extraClass}" aria-hidden="true"><use href="#i-${id}"/></svg>`;
}
